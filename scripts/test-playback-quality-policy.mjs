import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const app=fs.readFileSync('src/app.js','utf8');
const settingsJs=fs.readFileSync('src/play-settings.js','utf8');
const from=app.indexOf('  function getQualityPlan(activeSource, channel) {');
const to=app.indexOf('\n  function renderChannelSelectors()',from);
assert.ok(from>=0&&to>from);
const window={localStorage:{getItem:()=>null,setItem:()=>{}}};
window.window=window;
vm.runInNewContext(settingsJs,{window});
const policy=vm.runInNewContext(app.slice(from,to)+'\ngetQualityPlan',
  {global:window,MODERN_WEB:true,getPlaySettings:()=>current});
let current={qualityMode:'highest',fixedQuality:'flac32bit',autoFallback:true};
const plan=(q)=>Array.from(policy({sources:{kg:{qualitys:q}}},'kg'));
assert.deepEqual(plan(['128k','320k','flac32bit']),['flac32bit','320k','128k']);
assert.deepEqual(plan(['128k','320k','flac']),['flac','320k','128k']);
current={qualityMode:'fixed',fixedQuality:'flac32bit',autoFallback:true};
assert.deepEqual(plan(['128k','320k','flac']),['flac','320k','128k']);
assert.deepEqual(plan(['128k']),['128k']);
current={qualityMode:'fixed',fixedQuality:'flac32bit',autoFallback:false};
assert.deepEqual(plan(['128k','320k','flac']),[]);
current={qualityMode:'fixed',fixedQuality:'320k',autoFallback:true};
assert.deepEqual(plan(['128k','320k','flac']),['320k','128k']);
assert.deepEqual(plan([]),[]);
assert.ok(app.includes("name==='NotAllowedError'?'autoplay_policy'"));
assert.ok(app.includes("name==='NotSupportedError'?'unsupported_media'"));
assert.ok(app.includes("name==='AbortError'?'interrupted'"));
assert.ok(app.includes('id="resume-audio-on-gesture"'));
assert.ok(!app.includes('允许降到128k'));
console.log('FYMUSIC_AUTOPLAY_DIAGNOSTIC_AND_QUALITY_POLICY_PASS');
